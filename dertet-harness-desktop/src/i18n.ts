function detectSystemLang(): LangCode {
  const nav = (navigator.language || "uk").slice(0, 2).toLowerCase();
  return (LANGUAGES as readonly string[]).includes(nav) ? (nav as LangCode) : "uk";
}

interface I18nContextValue {
  lang: LangCode | "system";
  effectiveLang: LangCode;
  setLang: (l: LangCode | "system") => void;
  t: (key: string, ...args: string[]) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<LangCode | "system">("uk");

  useEffect(() => {
    const stored = window.localStorage.getItem("dertet_lang") as LangCode | "system" | null;
    if (stored) setLangState(stored);
  }, []);

  function setLang(l: LangCode | "system") {
    setLangState(l);
    window.localStorage.setItem("dertet_lang", l);
  }

  const effectiveLang: LangCode = lang === "system" ? detectSystemLang() : lang;

  useEffect(() => {
    // Backend-generated text (slash-command replies, agent activity labels) has no view of the
    // renderer's own language state otherwise — persisting the resolved code into Settings is what
    // lets agentLoop.ts match whatever language the UI is actually showing.
    dertet().settings.update({ language: effectiveLang }).catch(() => {});
  }, [effectiveLang]);

  function t(key: string, ...args: string[]): string {
    const dict = TRANSLATIONS[effectiveLang] ?? TRANSLATIONS.uk;
    let value = dict[key] ?? TRANSLATIONS.uk[key] ?? key;
    args.forEach((a, i) => {
      value = value.replace(`{${i}}`, a);
    });
    return value;
  }

  return React.createElement(I18nContext.Provider, { value: { lang, effectiveLang, setLang, t } }, children);
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
